#!/usr/bin/env python3
"""Check the static site before it is deployed.

Usage:
    python scripts/check_site.py site

Fails (exit code 1) if:
  * a required file is missing
  * an HTML page has no <title>
  * a local link or asset (href/src) points to a file that doesn't exist
  * an in-page link (#something) points to an id that doesn't exist

When run inside GitHub Actions, every problem is printed as an ::error::
annotation (so it shows up on the run page), and a summary table is
written to the job summary.

Standard library only, so no install step is needed.
"""
from __future__ import annotations

import os
import sys
from html.parser import HTMLParser
from pathlib import Path
from urllib.parse import unquote, urlsplit

REQUIRED_FILES = ["index.html", "styles.css", "app.js"]
# Generated by the workflow at build time, so it may not exist yet.
OPTIONAL_TARGETS = {"build-info.json"}


class PageParser(HTMLParser):
    def __init__(self) -> None:
        super().__init__()
        self.links: list[tuple[str, int]] = []   # (url, line)
        self.ids: set[str] = set()
        self.title = ""
        self._in_title = False

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if attrs.get("id"):
            self.ids.add(attrs["id"])
        for key in ("href", "src"):
            if attrs.get(key):
                self.links.append((attrs[key], self.getpos()[0]))
        if tag == "title":
            self._in_title = True

    def handle_endtag(self, tag):
        if tag == "title":
            self._in_title = False

    def handle_data(self, data):
        if self._in_title:
            self.title += data


def check(root: Path) -> list[tuple[str, int, str]]:
    problems: list[tuple[str, int, str]] = []

    for name in REQUIRED_FILES:
        if not (root / name).is_file():
            problems.append((str(root / name), 0, f"required file '{name}' is missing"))

    pages = sorted(root.rglob("*.html"))
    if not pages:
        problems.append((str(root), 0, "no .html files found"))

    for page in pages:
        parser = PageParser()
        parser.feed(page.read_text(encoding="utf-8"))

        if not parser.title.strip():
            problems.append((str(page), 1, "page has no <title>"))

        for url, line in parser.links:
            parts = urlsplit(url)
            if parts.scheme in ("http", "https", "mailto", "tel", "data"):
                continue                      # external links are not checked
            if not parts.path:                # "#anchor" on the same page
                if parts.fragment and parts.fragment not in parser.ids:
                    problems.append((str(page), line, f"link to missing anchor '#{parts.fragment}'"))
                continue
            target = (page.parent / unquote(parts.path)).resolve()
            if target.is_dir():
                target = target / "index.html"
            if not target.exists() and target.name not in OPTIONAL_TARGETS:
                problems.append((str(page), line, f"broken link or asset: '{url}'"))

    return problems


def main() -> int:
    root = Path(sys.argv[1] if len(sys.argv) > 1 else "site")
    if not root.is_dir():
        print(f"::error::folder '{root}' does not exist")
        return 1

    problems = check(root)
    files = len(list(root.rglob("*")))

    for path, line, message in problems:
        location = f"file={path},line={line}" if line else f"file={path}"
        print(f"::error {location}::{message}")

    status = "❌ failed" if problems else "✅ passed"
    print(f"Site check {status}: {files} files, {len(problems)} problem(s).")

    summary = os.environ.get("GITHUB_STEP_SUMMARY")
    if summary:
        with open(summary, "a", encoding="utf-8") as fh:
            fh.write(f"### Site check {status}\n\n")
            fh.write(f"Checked **{files}** files in `{root}/`.\n\n")
            if problems:
                fh.write("| File | Line | Problem |\n|---|---|---|\n")
                for path, line, message in problems:
                    fh.write(f"| `{path}` | {line or ''} | {message} |\n")

    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
